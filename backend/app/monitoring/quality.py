def _hits(text: str, markers: tuple[str, ...]) -> list[str]:
    return [x for x in markers if x in text]


def classify(
    text: str | None,
    intent: str | None = None,
    score: int | None = None,
) -> dict[str, Any]:

    t = (text or "").lower()
    intent = (intent or "").strip().lower()

    jobs = _hits(t, JOB_STRONG)
    promo = _hits(t, SELF_PROMO)
    education = _hits(t, EDUCATION)
    digest = _hits(t, DIGEST_AGGREGATOR)
    buy = _hits(t, BUY) + _hits(t, DEV_BUY)
    avito = _hits(t, AVITO)
    pain = _hits(t, PAIN)
    advice_demand = _hits(t, ADVICE_DEMAND)
    if (
        any(x in t for x in ("подскажите", "посоветуйте", "порекомендуйте", "как "))
        and any(x in t for x in (
            "авито", "avito", "авитолог", "crm", "срм", "коллтрекинг",
            "calltracking", "call tracking", "сквозн", "телефони", "ip-телефон",
            "ип-телефон", "виртуальн", "атс", "пропущенн", "звонк",
        ))
    ):
        advice_demand.append("service_advice_question")

    reasons=[]

    if intent == "job_post":
        reasons.append("intent_job_post")

    if intent == "offer_service":
        reasons.append("intent_offer_service")

    if jobs:
        reasons.append("job_language")

    if promo:
        reasons.append("self_promo")

    if education:
        reasons.append("education")

    if digest:
        reasons.append("digest_aggregator")

    reject = bool(reasons)

    demand = bool(
        intent == "buy_service"
        or buy
        or advice_demand
        or (avito and pain)
        or (pain and any(x in t for x in MARKETING_DOMAIN))
    )

    # Обычное профессиональное обсуждение не превращаем в лид. Но явный
    # прикладной вопрос по услугам BORIS (Avito/CRM/calltracking/telephony/
    # сквозная аналитика) считаем коммерческим advice-intent даже без фразы
    # «ищу исполнителя»: пользователь прямо просит решение задачи.
    if intent in {"ask_advice", "discussion"} and not buy and not advice_demand:
        demand = False

    return {
        "qualified": bool(not reject and demand),
        "reject": reject,
        "reasons": reasons,
        "intent": intent,
        "job_hits": jobs,
        "promo_hits": promo,
        "education_hits": education,
        "digest_hits": digest,
        "buy_hits": buy,
        "avito_hits": avito,
        "pain_hits": pain,
        "advice_demand_hits": advice_demand,
        "score": score,
    }
