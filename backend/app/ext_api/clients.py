NON_CLIENT_CEILING = 88


def prioritize():
    """Переставить приоритеты уже заведённых задач под правило владельца.

    Клиентские поднимаются, всё остальное опускается ниже клиентского порога.
    Функция идемпотентна: повторный запуск ничего не портит.
    """
    changed = []
    order_priority_repairs = []
    # Include recoverable blockers: when self-heal requeues them they must not
    # come back with a stale priority from an older scheduling decision.
    priority_sync_states = list(a2a.OPEN_STATES) + [a2a.BLOCKED_INFRA, a2a.BLOCKED_HUMAN]
    rows = db.rows("SELECT id, title, priority FROM ext_dev_jobs "
                   "WHERE status NOT IN ('completed','cancelled')")
    for r in rows:
        title = r["title"] or ""
        want = None
        for key, pr in CLIENT_PRIORITY.items():
            if title.startswith(key):
                want = pr
                break
        if want is None:
            for key, pr in PRIORITY_OVERRIDES.items():
                if title.startswith(key):
                    want = pr
                    break
        if want is None:
            want = min(int(r["priority"] or 50), NON_CLIENT_CEILING)
        if int(r["priority"] or 0) != want:
            db.q("UPDATE ext_dev_jobs SET priority=:p, updated_at=NOW() WHERE id=:i",
                 p=want, i=r["id"])
            changed.append({"dev_job_id": "dev_%s" % r["id"], "title": title[:60],
                            "was": r["priority"], "now": want})

        # PRIORITY_DRIFT_SELF_HEAL_V1: dev_job and its live A2A order are one
        # scheduling decision. Updating child orders only when the parent value
        # changed leaves permanent drift after a manual/admin priority change
        # or a partially completed recovery tick. Then the queue can execute a
        # lower-priority task before the owner's/client's current critical path.
        # Repair the open orders idempotently on every dispatcher cycle.
        drift = db.rows("""SELECT id, priority FROM ext_a2a_orders
                           WHERE dev_job_id=:i AND status = ANY(:st)
                             AND priority<>:p
                           ORDER BY id""",
                        i=r["id"], st=priority_sync_states, p=want)
        if drift:
            db.q("""UPDATE ext_a2a_orders SET priority=:p, updated_at=NOW()
                     WHERE dev_job_id=:i AND status = ANY(:st)
                       AND priority<>:p""",
                 p=want, i=r["id"], st=priority_sync_states)
            order_priority_repairs.append({
                "dev_job_id": "dev_%s" % r["id"],
                "order_ids": [int(x["id"]) for x in drift],
                "from": sorted({int(x.get("priority") or 0) for x in drift}),
                "now": want,
            })
    return {
        "changed": changed,
        "order_priority_repairs": order_priority_repairs,
        "rule": "клиенты от %d и выше, остальное не выше %d"
                % (min(CLIENT_PRIORITY.values()), NON_CLIENT_CEILING),
    }


