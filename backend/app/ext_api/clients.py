def assert_business_contract(key):
    """Нет критериев бизнес-приёмки — нет задачи."""
    if not str(key).startswith("CLIENT_") and key not in BUSINESS_CONTRACT:
        return True
    c = BUSINESS_CONTRACT.get(key) or {}
    missing = [f for f in CONTRACT_FIELDS if not c.get(f)]
    if missing or key not in BUSINESS_GOAL:
        raise ApiError("NO_BUSINESS_CONTRACT",
                       "клиентская задача без критериев бизнес-приёмки не "
                       "заводится: не хватает %s"
                       % (", ".join(missing + ([] if key in BUSINESS_GOAL
                                               else ["business_goal"]))))
    return True


def business_registry_health():
    """Runtime invariant for DETECT -> RECOVER coverage.

    Every business goal must have both a measurable contract and a CLIENTS
    recovery specification. Extra contracts are also suspicious because they
    can silently drift from the actual monitored goal set.
    """
    goal_keys = set(BUSINESS_GOAL)
    contract_keys = set(BUSINESS_CONTRACT)
    specs = {
        str(row.get("key")): row
        for row in CLIENTS
        if row.get("key")
    }
    spec_keys = set(specs)
    missing_contract = sorted(goal_keys - contract_keys)
    extra_contract = sorted(contract_keys - goal_keys)
    missing_spec = sorted(goal_keys - spec_keys)
    incomplete_contract = {}
    incomplete_spec = {}
    for key in sorted(goal_keys):
        contract = BUSINESS_CONTRACT.get(key) or {}
        missing = [field for field in CONTRACT_FIELDS if not contract.get(field)]
        if missing:
            incomplete_contract[key] = missing
        spec = specs.get(key) or {}
        spec_missing = []
        if not ((spec.get("scope") or {}).get("paths") or []):
            spec_missing.append("scope.paths")
        if not (spec.get("acceptance") or []):
            spec_missing.append("acceptance")
        if not spec.get("first_order"):
            spec_missing.append("first_order")
        if spec_missing:
            incomplete_spec[key] = spec_missing
    ok = not (
        missing_contract
        or extra_contract
        or missing_spec
        or incomplete_contract
        or incomplete_spec
    )
    return {
        "ok": ok,
        "goal_count": len(goal_keys),
        "contract_count": len(contract_keys),
        "recovery_spec_count": len(goal_keys & spec_keys),
        "missing_contract": missing_contract,
        "extra_contract": extra_contract,
        "missing_spec": missing_spec,
        "incomplete_contract": incomplete_contract,
        "incomplete_spec": incomplete_spec,
    }


def _reopen_terminal_receipts_if_business_regressed(job, truth_row):
    """Снять старый DONE-fence только по свежей полной измеримой регрессии.

    Старый cancelled order остаётся историей. Меняется только blocker-marker,
    чтобы durable create/scheduler fence не запрещал новый шаг клиенту после
    доказанного ухудшения production-результата.
    """
    if not job or not truth_row:
        return []
    if truth_row.get("overall_done"):
        return []
    if not truth_row.get("measurable") or not truth_row.get("contract_measurable"):
        return []
    rows = db.rows("""
        UPDATE ext_a2a_orders
           SET blocked_reason='business_goal_regressed_after_fresh_truth',
               updated_at=NOW()
         WHERE dev_job_id=:d
           AND blocked_reason='business_goal_already_confirmed'
        RETURNING id
    """, d=int(job["id"]))
    reopened = [int(r["id"]) for r in rows]
    for oid in reopened:
        a2a.message(
            oid, "BUSINESS_GOAL_REOPENED", "business_truth",
            {
                "why": "fresh measurable client contract is no longer complete",
                "client": truth_row.get("key"),
                "state": truth_row.get("state"),
                "proof": truth_row.get("proof"),
            },
        )
    if reopened:
        dev.event(
            job["id"], job.get("current_phase") or "PLANNING",
            "business_truth", "business_goal_reopened",
            {
                "order_ids": reopened,
                "state": truth_row.get("state"),
                "proof": truth_row.get("proof"),
            },
        )
    return reopened


def _terminalize_recovery_if_business_done(job, truth_row):
    """Close an obsolete recovery lifecycle when fresh business truth is DONE.

    A recovery dev-job is only a vehicle to restore a client outcome. If fresh,
    measurable production truth already proves that outcome, keeping the
    recovery row blocked/waiting is false operational debt and can keep priority
    100 work visible forever. Cancel the obsolete lifecycle, preserve durable
    proof, and release any execution ownership. Historical accepted/cancelled
    evidence remains untouched.
    """
    if not job or not truth_row or not truth_row.get("overall_done"):
        return False
    if not truth_row.get("measurable") or not truth_row.get("contract_measurable"):
        return False
    request_id = str(job.get("request_id") or "")
    if not request_id.startswith("business_recovery:"):
        return False
    if job.get("status") in ("completed", "cancelled"):
        return False

    job_id = int(job["id"])
    db.q(
        """UPDATE ext_a2a_orders
              SET status='cancelled',
                  blocked_reason='business_goal_already_confirmed',
                  claimed_by=NULL,
                  claimed_at=NULL,
                  updated_at=NOW()
            WHERE dev_job_id=:d
              AND status NOT IN ('accepted','cancelled')""",
        d=job_id,
    )
    final_result = {
        "WHAT_CHANGED": "recovery lifecycle closed because fresh business truth is already DONE",
        "REAL_RESULT": {
            "status": "cancelled",
            "reason": "business_goal_already_confirmed",
            "client": truth_row.get("key"),
            "state": truth_row.get("state"),
            "progress": truth_row.get("progress"),
            "proof": truth_row.get("proof"),
        },
        "NEXT_STEP": "не требуется: клиентский бизнес-результат подтверждён",
    }
    db.q(
        """UPDATE ext_dev_jobs
              SET status='cancelled',
                  assigned_agent=NULL,
                  wait_reason=NULL,
                  blocked_reason=NULL,
                  final_result_json=:result,
                  updated_at=NOW()
            WHERE id=:d
              AND status NOT IN ('completed','cancelled')""",
        d=job_id,
        result=json.dumps(final_result, ensure_ascii=False),
    )
    dev.event(
        job_id,
        job.get("current_phase") or "PLANNING",
        "business_truth",
        "business_recovery_terminalized_goal_already_done",
        {
            "client": truth_row.get("key"),
            "state": truth_row.get("state"),
            "progress": truth_row.get("progress"),
            "proof": truth_row.get("proof"),
        },
    )
    dev.release(job_id)
    return True


def _recovery_job_if_business_regressed(key, goal, job, truth_row):
    """Create one durable recovery lifecycle after a terminal business regression."""
    if not job or job.get("status") not in ("completed", "cancelled"):
        return job, False
    if truth_row.get("overall_done"):
        return job, False
    if not truth_row.get("measurable") or not truth_row.get("contract_measurable"):
        return job, False

    request_id = "business_recovery:%s:after:%s" % (key, int(job["id"]))
    existing = db.one(
        "SELECT id FROM ext_dev_jobs WHERE request_id=:r ORDER BY id DESC LIMIT 1",
        r=request_id,
    )
    if existing:
        return dev.get(existing["id"]), False

    spec = next((s for s in CLIENTS if s.get("key") == key), None)
    if not spec:
        return job, False

    recovery = dev.create(
        LEAD_KEY,
        request_id,
        "%s — recovery после измеримой regression" % key,
        (
            "Свежая production business-truth доказала регрессию после ранее "
            "завершённого lifecycle. Восстановить бизнес-результат: %s. "
            "Историческую completed-задачу не переписывать. Текущий proof: %s"
            % (goal, str(truth_row.get("proof") or "")[:1000])
        ),
        [
            "Найдена и устранена первопричина свежей измеримой регрессии",
            "Свежая business_truth снова подтверждает overall_done=true",
            "Production QA подтверждает восстановленный клиентский результат",
        ],
        scope=spec.get("scope") or {},
        owner=EXECUTOR,
        priority=CLIENT_PRIORITY.get(key, 95),
    )
    dev.event(
        recovery["id"],
        "PLANNING",
        "business_truth",
        "recovery_created_after_terminal_regression",
        {
            "client": key,
            "previous_dev_job_id": job["id"],
            "state": truth_row.get("state"),
            "proof": truth_row.get("proof"),
        },
    )
    return recovery, True


def ensure_business_orders():
    """Гарантировать следующий наряд, пока бизнес-цель клиента не достигнута.

    Технический ACCEPT/REVIEW не является финалом. Если открытого исполнимого
    наряда нет, а production-gate ещё не достигнут, создаём следующий шаг
    идемпотентно. Это закрывает дыру, когда старый review_requested считался
    «живым» в одном отчёте, но исполнитель уже не мог продолжать работу.
    """
    from . import report as _report
    made = []
    truth = {r.get("key"): r for r in _report.business_truth(2, fresh=True).get("clients", [])}
    for key, goal in BUSINESS_GOAL.items():
        job = _existing(key)
        if not job:
            continue
        tr = truth.get(key) or {}

        # A terminal lifecycle is historical evidence, not a permanent immunity
        # from future measurable regressions. Create one new recovery lifecycle;
        # never rewrite the old completed/cancelled row.
        if job["status"] in ("completed", "cancelled"):
            job, recovery_created = _recovery_job_if_business_regressed(
                key, goal, job, tr
            )
            if recovery_created:
                made.append({
                    "client": key,
                    "recovery_dev_job_id": job["dev_job_id"],
                    "goal": goal,
                })
            if job["status"] in ("completed", "cancelled"):
                continue

        if tr.get("overall_done"):
            orders = a2a.listing(dev_job_id=job["dev_job_id"], limit=100)
            # Goal already proved: obsolete queued/returned business orders must
            # not consume executor capacity or mutate an already-correct client.
            for old in orders:
                if ("БИЗНЕС-РЕЗУЛЬТАТ:" in (old.get("goal") or "") and
                        old.get("status") in (a2a.OPEN_STATES + (a2a.BLOCKED_HUMAN, a2a.BLOCKED_INFRA))):
                    # BUSINESS_GOAL_DONE_CANCEL_ALL_OPEN_V1: once fresh business
                    # truth proves the client result, blocked/review/running
                    # technical orders are obsolete too. Leaving a blocked_infra
                    # order alive makes the scheduler believe a completed client
                    # still needs a coding provider and can trigger paid/free AI
                    # retries for no customer benefit.
                    db.q("UPDATE ext_a2a_orders SET status='cancelled', blocked_reason=:r, claimed_by=NULL, claimed_at=NULL, updated_at=NOW() WHERE id=:i",
                         r="business_goal_already_confirmed", i=old["order_id"])
            # BUSINESS_RECOVERY_TERMINAL_ON_FRESH_DONE_V1: a recovery lifecycle
            # itself must not stay blocked/waiting after its client outcome is
            # freshly proven. Close only recovery:* rows; historical canonical
            # dev jobs keep their technical lifecycle untouched.
            _terminalize_recovery_if_business_done(job, tr)
            continue

        # BUSINESS_GOAL_FRESH_REGRESSION_REOPEN_V1: old DONE evidence must not
        # freeze a client forever. Reopen only when every required metric was
        # measured successfully and the fresh contract is definitely incomplete.
        # If telemetry itself is unavailable, keep the historical fence and fail
        # closed instead of spawning speculative duplicate work.
        _reopen_terminal_receipts_if_business_regressed(job, tr)
        orders = a2a.listing(dev_job_id=job["dev_job_id"], limit=100)

        # Only work that an executor can actually continue blocks creation.
        executable = [o for o in orders if o["status"] in (a2a.QUEUED, a2a.RUNNING, a2a.RETURNED)]
        if executable:
            continue
        mark = "БИЗНЕС-РЕЗУЛЬТАТ: " + goal[:50]
        # Idempotency: an already-created non-terminal business order is enough.
        if any(mark in (o.get("goal") or "") and o.get("status") in
               (a2a.QUEUED, a2a.RUNNING, a2a.RETURNED) for o in orders):
            continue
        text = (GENERATION_ALLOWED + "\n\n" + SOURCE_OF_TRUTH +
                "\n\nБИЗНЕС-РЕЗУЛЬТАТ: %s\n\n"
                "Фактический прогресс сейчас: %s%%. Нужен именно измеримый "
                "результат для клиента. Что можно сделать штатными средствами — "
                "сделать автономно; технический блокер чинить самостоятельно; "
                "владельца тревожить только если без его решения физически нельзя продолжить."
                % (goal, tr.get("progress") if tr.get("progress") is not None else "не измерен"))
        o = a2a.create_order(LEAD_KEY, job["dev_job_id"],
                             job.get("current_phase") or "BACKEND", text,
                             scope=job.get("scope") or {},
                             acceptance=["Клиент получил: " + goal,
                                         "Результат подтверждён фактами: запросом к базе или обходом кабинета"],
                             forbidden=COMMON_FORBIDDEN, required_qa=["db_query"],
                             required_evidence=["вывод db_query"], assigned_to=EXECUTOR,
                             max_iterations=6, priority=CLIENT_PRIORITY.get(key, 95))
        made.append({"client": key, "order_id": o["order_id"], "goal": goal})
    return made


def _existing(key):
    # The newest canonical/recovery lifecycle is authoritative. Choosing the
    # oldest row makes a fresh recovery invisible behind historical completed.
    r = db.one("SELECT id FROM ext_dev_jobs WHERE title LIKE :p ORDER BY id DESC LIMIT 1",
               p=f"{key}%")
    return dev.get(r["id"]) if r else None


def create(with_orders=True):
    out = []
    for spec in CLIENTS:
        assert_business_contract(spec["key"])
        job = _existing(spec["key"])
        created = False
        if not job:
            job = dev.create(LEAD_KEY, f"req_{spec['key'].lower()}", spec["title"],
                             spec["goal"], spec["acceptance"],
                             scope=spec["scope"], owner=EXECUTOR)
            created = True
        orders = a2a.listing(dev_job_id=job["dev_job_id"], limit=20)
        order = None
        terminal_business = int(str(job["dev_job_id"]).replace("dev_", "")) in dev.business_goal_terminal_job_ids()
        # BUSINESS_GOAL_CREATE_TERMINAL_FENCE_V1: bootstrap/create is allowed to
        # recreate missing work, but never after the latest canonical business
        # order was closed because fresh production truth proved the goal.
        first_order = spec.get("first_order")
        # CLIENT_BOOTSTRAP_OPTIONAL_FIRST_ORDER_V1: some monitoring/business
        # records intentionally have no bootstrap executor prompt. Creating the
        # registry must not crash after processing earlier clients.
        if with_orders and first_order and not terminal_business and not [o for o in orders if o["status"] != a2a.CANCELLED]:
            order = a2a.create_order(
                LEAD_KEY, job["dev_job_id"], "PLANNING", first_order,
                scope=spec["scope"], acceptance=spec["acceptance"],
                forbidden=COMMON_FORBIDDEN,
                required_qa=["db_query", "repo_read"],
                required_evidence=["вывод db_query", "вывод repo_read или repo_tree"],
                assigned_to=EXECUTOR, max_iterations=6, priority=60)
        out.append({"client": spec["key"], "dev_job_id": job["dev_job_id"],
                    "job_created": created, "title": spec["title"],
                    "order_id": (order or {}).get("order_id"),
                    "existing_orders": [o["order_id"] for o in orders]})
    return out


def status():
    out = []
    for spec in CLIENTS:
        job = _existing(spec["key"])
        if not job:
            out.append({"client": spec["key"], "state": "не заведена"})
            continue
        orders = a2a.listing(dev_job_id=job["dev_job_id"], limit=20)
        done = [c for c in job["acceptance_criteria"] if (c or {}).get("done")]
        out.append({"client": spec["key"], "dev_job_id": job["dev_job_id"],
                    "status": job["status"], "phase": job["current_phase"],
                    "acceptance": f"{len(done)}/{len(job['acceptance_criteria'])}",
                    "orders": [{"id": o["order_id"], "status": o["status"],
                                "iteration": f"{o['iteration']}/{o['max_iterations']}",
                                "blocked": o["blocked_reason"]} for o in orders]})
    return out


def reset(order_id=None, only_blocked=True):
    """Вернуть застрявшие наряды в работу — после того, как устранена причина.

    Предохранитель останавливает цикл намеренно; когда первопричина починена,
    наряд надо явно вернуть в очередь, а не заводить новый и терять историю.
    """
    if order_id:
        targets = [a2a.get(order_id, with_messages=False)]
    else:
        targets = [o for o in a2a.listing(limit=200)
                   if (o["status"] in (a2a.BLOCKED_INFRA, a2a.FAILED) if only_blocked
                       else o["status"] not in (a2a.ACCEPTED, a2a.CANCELLED))]
    out = []
    for o in targets:
        if o["status"] in (a2a.ACCEPTED, a2a.CANCELLED):
            continue
        a2a._set(o["order_id"], status=a2a.QUEUED, iteration=0, blocked_reason=None)
        a2a.message(o["order_id"], "RESET", "claude-lead",
                    {"was": o["status"], "was_iteration": o["iteration"],
                     "why": "первопричина устранена, наряд возвращён в очередь"})
        out.append({"order_id": o["order_id"], "was": o["status"],
                    "now": a2a.QUEUED})
    return out


def log(order_id=None, dev_job_id=None, limit=1):
    """Полная переписка агентов по наряду — читаемым текстом.

    На доске владельцу показываются только исходы, но переписка никуда не
    прячется: она вся лежит в базе и достаётся вот этим.
    """
    if order_id:
        ids = [int(order_id)]
    else:
        ids = [o["order_id"] for o in a2a.listing(dev_job_id=dev_job_id, limit=limit)]
    out = []
    for oid in ids:
        o = a2a.get(oid)
        lines = [
            "=" * 78,
            f"НАРЯД {o['order_id']} · задача {o['dev_job_id']} · фаза {o['phase']}",
            f"статус {o['status']} · итерация {o['iteration']}/{o['max_iterations']} · "
            f"поставил {o['created_by']} · исполняет {o['assigned_to']}",
            f"ЦЕЛЬ: {o['goal']}",
            "КРИТЕРИИ: " + "; ".join(o["acceptance_criteria"]),
        ]
        if o["blocked_reason"]:
            lines.append(f"БЛОКЕР: {o['blocked_reason']}")
        for m in o["messages"]:
            b = m["body"] or {}
            lines += ["", f"--- {m['kind']} · {m['author']} · {m['at']}"]
            if m["kind"] == "REVIEW_REQUEST":
                lines.append(f"итог: {b.get('summary')}")
                for c in b.get("acceptance_criteria") or []:
                    lines.append(f"  [{c.get('status')}] {c.get('criterion')}")
                    if c.get("evidence"):
                        lines.append(f"        доказательство: {str(c['evidence'])[:400]}")
                if b.get("build"):
                    lines.append(f"сборка: {b['build']}")
                if b.get("tests"):
                    lines.append(f"тесты: {b['tests']}")
                if b.get("evidence"):
                    lines.append("вывод команд:")
                    lines += ["  " + l for l in str(b["evidence"])[:3000].split("\n")]
                if b.get("blockers"):
                    lines.append(f"блокеры: {b['blockers']}")
            elif m["kind"] == "RETURN_WITH_FIXES":
                lines.append(f"замечание лида: {b.get('note')}")
                for f in b.get("fixes") or []:
                    lines.append(f"  критерий: {f.get('failed_criterion')}")
                    lines.append(f"  проблема: {f.get('problem')}")
                    lines.append(f"  исправить: {f.get('required_correction')}")
            elif m["kind"] == "EXECUTOR_ORDER":
                lines.append(f"цель: {b.get('goal')}")
                lines.append(f"запрещено: {b.get('forbidden_changes')}")
            else:
                lines.append(json.dumps(b, ensure_ascii=False)[:800])
        runs = db.rows("""SELECT provider, model, iteration, steps, tool_calls,
                                 prompt_tokens, completion_tokens, outcome
                          FROM ext_a2a_runs WHERE order_id=:o ORDER BY id""", o=oid)
        for r in runs:
            lines.append(f"расход: {r['provider']} {r['model']}, итерация {r['iteration']}, "
                         f"шагов {r['steps']}, вызовов {r['tool_calls']}, "
                         f"токенов {r['prompt_tokens']}+{r['completion_tokens']} -> {r['outcome']}")
        out.append("\n".join(lines))
    return "\n\n".join(out) or "нарядов не найдено"


