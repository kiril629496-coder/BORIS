UNBLOCK_CAP = int(os.environ.get("BORIS_UNBLOCK_CAP", "12"))


def unblock_clients(cap=None):
    """Снять блокировку — но только с действующего наряда каждой задачи.

    21.08 прошлая версия сняла ограничение с 18 521 наряда разом: она брала
    всё с префиксом CLIENT_ и не различала действующую фазу и историю. Очередь
    выросла до 32 692, и настоящие клиенты в ней потерялись. Здесь три
    предохранителя:

      · по задаче берётся ровно один наряд — самый свежий;
      · терминальные статусы не воскресают никогда;
      · есть потолок на один проход, и превышение — это отказ, а не «ну
        ладно, разблокирую всё».
    """
    limit = int(UNBLOCK_CAP if cap is None else cap)
    rows = db.rows("""SELECT DISTINCT ON (o.dev_job_id)
                             o.id, o.goal, o.blocked_reason, o.dev_job_id, j.title
                        FROM ext_a2a_orders o
                        JOIN ext_dev_jobs j ON j.id = o.dev_job_id
                       WHERE o.status IN ('blocked_human', 'blocked_infra')
                         AND j.title LIKE 'CLIENT!_%' ESCAPE '!'
                         AND j.status NOT IN ('completed', 'cancelled')
                       ORDER BY o.dev_job_id, o.id DESC""")
    if len(rows) > limit:
        # Fail-closed: столько сразу разблокировать нельзя. Разбираться с
        # накопленной историей — работа queuefix, а не этой функции.
        return [{"stopped": True,
                 "why": "к разблокировке подошло %d нарядов при потолке %d — "
                        "остановлено, нужен разбор очереди" % (len(rows), limit)}]
    freed = []
    for r in rows:
        goal = r.get("goal") or ""
        if SOURCE_OF_TRUTH[:40] not in goal:
            goal = GENERATION_ALLOWED + "\n\n" + SOURCE_OF_TRUTH + "\n\n" + goal
        a2a._set(r["id"], status=a2a.QUEUED, blocked_reason=None, iteration=0,
                 claimed_by=None, claimed_at=None, goal=goal[:20000])
        a2a.message(r["id"], "RESET", "claude-lead",
                    {"note": SOURCE_OF_TRUTH,
                     "why": "владелец ответил на этот вопрос: фактура в профиле "
                            "компании, цены пропускаем, баннер выбирает исполнитель"})
        freed.append({"order_id": r["id"], "title": r["title"],
                      "was": (r.get("blocked_reason") or "")[:80]})
    return freed


def unblock_generation():
    return unblock_clients()


def unblock_loopguard():
    """Наряд остановлен лимитом итераций — но с новой вводной он не повтор.

    Шесть кругов «данных нет» случились из-за неверного источника. Держать
    такой наряд заблокированным после того, как владелец назвал источник, —
    значит терять клиента на формальности.
    """
    rows = db.rows("""SELECT o.id, o.dev_job_id, o.blocked_reason, j.title
                        FROM ext_a2a_orders o
                        JOIN ext_dev_jobs j ON j.id = o.dev_job_id
                       WHERE o.status = 'blocked_infra'
                         AND LOWER(COALESCE(o.blocked_reason,'')) LIKE '%итерац%'""")
    freed = []
    for r in rows:
        if not (r.get("title") or "").startswith("CLIENT_"):
            continue
        a2a._set(r["id"], status=a2a.QUEUED, blocked_reason=None, iteration=0,
                 claimed_by=None, claimed_at=None)
        a2a.message(r["id"], "EXECUTOR_ORDER", "claude-lead",
                    {"note": SOURCE_OF_TRUTH,
                     "why": "круги были из-за неверного источника фактуры; "
                            "владелец указал, где она лежит — счётчик сброшен"})
        freed.append({"order_id": r["id"], "title": r["title"]})
    return freed
