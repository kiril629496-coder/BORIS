def push_extra(force=False, only=None):
    """Довесить наряды по уточнённым требованиям владельца, без дублей.

    force=True ставит наряд, даже если по задаче уже идёт работа: владелец
    прислал факт с боевого экрана, и это важнее очереди.
    """
    out = []
    for spec in EXTRA_ORDERS:
        if only and spec["job"] != only:
            continue
        job = _existing(spec["job"])
        if not job:
            out.append({"job": spec["job"], "skipped": "задача не заведена"})
            continue
        mark = spec["goal"][:60]
        existing = a2a.listing(dev_job_id=job["dev_job_id"], limit=50)
        if any(mark in (o["goal"] or "") for o in existing):
            out.append({"job": spec["job"], "skipped": "такой наряд уже есть"})
            continue
        if not force and any(o["status"] in a2a.OPEN_STATES for o in existing):
            out.append({"job": spec["job"], "skipped": "по задаче уже идёт работа"})
            continue
        dev.add_criteria(LEAD_KEY, job["dev_job_id"], spec["acceptance"],
                         why="уточнение требований владельца")
        o = a2a.create_order(LEAD_KEY, job["dev_job_id"], spec["phase"], spec["goal"],
                             scope=job.get("scope") or {}, acceptance=spec["acceptance"],
                             forbidden=COMMON_FORBIDDEN,
                             required_qa=["db_query", "repo_read"],
                             required_evidence=["вывод db_query"],
                             assigned_to=EXECUTOR, max_iterations=6,
                             priority=int(spec.get("priority", 80)))
        out.append({"job": spec["job"], "order_id": o["order_id"], "phase": o["phase"]})
    return out


