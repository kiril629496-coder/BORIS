def factual_niche_example(topic: str, payload: dict) -> tuple[str, dict] | None:
    """Return proven item specifics, or an explicit needs-data result."""
    kind = _kind(topic)
    if kind is None:
        return None
    p = payload if isinstance(payload, dict) else {}
    facts = []
    for label, key in FIELDS[kind]:
        value = _clean(p.get(key))
        if value:
            facts.append((label, value))
    meta = {
        "present": len(facts) >= 2,
        "position": "bottom", "policy": "niche_factual_items_v1",
        "needs_data": len(facts) < 2,
        "fact_count": len(facts),
    }
    if len(facts) < 2:
        return "", meta
    label = "Пример товара" if kind in {"building", "furniture"} else "Пример услуги"
    if kind == "estate":
        label = "Пример квартиры"
    return ("<strong>" + label + ":</strong> " +
            "; ".join(f"{k}: {v}" for k, v in facts) + "."), meta
