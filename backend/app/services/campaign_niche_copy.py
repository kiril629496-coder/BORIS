def _kind(topic: str) -> str | None:
    low = str(topic or "").casefold().replace("ё", "е")
    if "душ" in low and ("стекл" in low or "перегород" in low):
        return "shower"
    if any(w in low for w in ("металлочереп", "профнастил", "кровл", "фасадн", "сайдинг")):
        return "building"
    if any(w in low for w in ("панорамн", "остеклен", "окна", "оконн", "витраж", "балкон", "лоджи")):
        return "glazing"
    if any(w in low for w in ("кухн", "кухон", "шкаф", "гардероб", "прихож", "мебел")):
        return "furniture"
    if "ипотек" in low:
        return "mortgage"
    if any(w in low for w in ("подбор квартир", "подбор жилья", "покупк квартир", "недвижим")):
        return "estate"
    return None


def _clean(value: object) -> str:
    if not isinstance(value, (str, int, float)) or isinstance(value, bool):
        return ""
    text = " ".join(str(value).split()).strip(" ,;.")
    if len(text) > 110 or not text or text.casefold() in {
        "null", "none", "неизвестно", "не указано", "по запросу",
        "по спецификации", "по выбранному варианту", "уточняется",
    }:
        return ""
    return text


def _bold(title: str, message: str) -> str:
    return "<strong>" + title + "</strong>\n" + message


