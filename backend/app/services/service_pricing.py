def _row(
    key, title, demand, mvp_days, mvp_cash, mvp_sell, full_sell, monthly_cogs,
    stack, result, full_days=None
):
    labor = int(mvp_days * HOURS_PER_DAY * INTERNAL_HOURLY_COST)
    cash_mid = int(sum(mvp_cash) / 2)
    return {
        "key": key,
        "title": title,
        "demand": demand,
        "result": result,
        "mvp_days": mvp_days,
        "full_days": full_days or max(mvp_days + 5, int(mvp_days * 2.5)),
        "mvp_direct_cash_from": mvp_cash[0],
        "mvp_direct_cash_to": mvp_cash[1],
        "mvp_labor_cost_estimate": labor,
        "mvp_total_internal_cost_estimate": labor + cash_mid,
        "mvp_sell_from": mvp_sell[0],
        "mvp_sell_to": mvp_sell[1],
        "full_sell_from": full_sell[0],
        "full_sell_to": full_sell[1],
        "monthly_cogs_from": monthly_cogs[0],
        "monthly_cogs_to": monthly_cogs[1],
        "stack": stack,
    }

