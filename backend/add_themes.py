RULES = """
ПОЗИЦИОНИРОВАНИЕ (из аудита рынка СПб):
- Пиши для прораба, снабженца и подрядчика, а не для дачника. Основные деньги
  приносят те, кто закрывает объект: берут несколько бытовок, арендуют месяцами,
  платят безналом, возвращаются на следующий объект.
- Называй позицию по ЗАДАЧЕ покупателя («для бригады», «пост охраны», «под
  инструмент»), а не по размеру корпуса.
- Продавай готовое решение, а не коробку: корпус плюс доставка, электрика, мебель.
- Условия сделки сильнее цены. Выноси вперёд наличие, срок доставки, безнал,
  документы, манипулятор, выкуп после аренды, работу по области.
- НЕ используй штампы рынка: «собственное производство», «работаем 20 лет»,
  «качественные материалы», «лучшие цены», «гарантия» без конкретики.

⛔ ЦЕНЫ: называть МОЖНО только подтверждённые цены компании (аренда 7 000,
ИТР 8 000, распашонка 9 000 руб/мес, залог 10 000, мебель 500 руб/шт.,
минимальный срок 30 дней). Рыночные диапазоны из аналитики — НЕ наши цены,
в постах их не приводить. Стоимость доставки не называть.
"""


def keys(s):
    return {w[:5] for w in re.findall(r"[а-яёa-z]{4,}", s.lower())} - STOP


db = SessionLocal()
row = db.execute(text("SELECT value FROM storage WHERE account_id=:a"
                      " AND key='posting_projects'"), {"a": BUCKET}).fetchone()
data = row[0] if isinstance(row[0], (list, dict)) else json.loads(row[0])
projects = data if isinstance(data, list) else [data]
hit = next((p for p in projects if p.get("id") == PID), None)
if hit is None:
    print("проект не найден"); sys.exit(1)

old_themes = hit.get("themes") or []
old_keys = [keys(t) for t in old_themes]
added, skipped = [], []
for t in NEW:
    k = keys(t)
    if any(len(k & ok) >= 2 for ok in old_keys):
        skipped.append(t)
    else:
        added.append(t)
        old_keys.append(k)

prompt = hit.get("text_prompt") or ""
prompt_new = prompt if "ПОЗИЦИОНИРОВАНИЕ" in prompt else (prompt.rstrip() + "\n" + RULES)

print("РЕЖИМ:", "ЗАПИСЬ" if APPLY else "ПРОСМОТР")
print("тем было %s | добавляем %s | похожие пропущены %s | станет %s"
      % (len(old_themes), len(added), len(skipped), len(old_themes) + len(added)))
print("промт: %s → %s символов" % (len(prompt), len(prompt_new)))
print("\nПРОПУЩЕНЫ КАК ПОХОЖИЕ:")
for t in skipped:
    print("  ~", t[:70])
print("\nДОБАВЛЯЕМ:")
for t in added:
    print("  +", t[:70])
if not APPLY:
    print("\nничего не записано, повторите с --apply")
    sys.exit(0)

hit["themes"] = old_themes + added
hit["text_prompt"] = prompt_new
db.execute(text("UPDATE storage SET value=:v WHERE account_id=:a"
                " AND key='posting_projects'"),
           {"v": json.dumps(data, ensure_ascii=False), "a": BUCKET})
db.commit(); db.close()
print("\nзаписано: тем %s, промт %s символов" % (len(old_themes) + len(added), len(prompt_new)))
