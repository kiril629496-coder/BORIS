def norm(t):
    return " ".join(str(t).lower().split())


db = SessionLocal()
row = db.query(Storage).filter(Storage.account_id == ACC,
                               Storage.key == "posting_projects").first()
if not row:
    raise SystemExit("нет ключа posting_projects у %s" % ACC)
projects = json.loads(row.value)

hit = None
for p in projects:
    if NAME_HINT in str(p.get("name", "")).lower():
        hit = p
        break
if not hit:
    raise SystemExit("проект с «%s» не найден. Есть: %s"
                     % (NAME_HINT, [p.get("name") for p in projects]))

old = hit.get("themes") or []
have = {norm(t) for t in old}
added = [t for t in THEMES if norm(t) not in have]
print("проект: %s" % hit.get("name"))
print("было тем: %d | добавляю: %d | станет: %d" % (len(old), len(added), len(old) + len(added)))
for t in added[:8]:
    print("   +", t)
if len(added) > 8:
    print("   … и ещё %d" % (len(added) - 8))

if APPLY:
    # В storage НЕТ уникального индекса (account_id, key) — ON CONFLICT не работает.
    # Бэкап делаем обычной вставкой через ORM, ключ уникален по времени.
    bak_key = "posting_projects_bak_%d" % int(time.time())
    bak_row = Storage(account_id=ACC, key=bak_key, value=row.value)
    db.add(bak_row)
    db.flush()
    print("бэкап прежнего значения: ключ", bak_key)
    hit["themes"] = old + added
    row.value = json.dumps(projects, ensure_ascii=False)
    db.commit()
    print("ЗАПИСАНО. Бэкап прежнего значения сохранён отдельным ключом")
