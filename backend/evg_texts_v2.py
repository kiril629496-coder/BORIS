def build(t, k):
    tid, titles, offer, pain, case, know_h, know, keys = t
    body = (offer + "\n\n" + pain + "\n\n📝 <strong>ПРИМЕР МОЕЙ РАБОТЫ</strong>\n" + case +
            "\n\n👍 <strong>" + know_h + "</strong>\n" + "\n".join("• " + p for p in know) +
            TAIL % (PRICE, keys))
    return tid, titles[k % len(titles)], body

