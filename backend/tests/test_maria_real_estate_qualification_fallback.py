from app.api.messenger import _mop_emergency_next_question

QUESTIONS = [
    "Мягко выяснить задачу клиента",
    "Район или метро",
    "Новостройка или вторичный рынок",
    "Комнатность",
    "Бюджет",
    "Наличные или ипотека",
    "Предложить короткий созвон, если это уместно",
    "Получить номер телефона для созвона, если клиент согласен",
]


def test_budget_and_mortgage_do_not_jump_straight_to_phone():
    history = (
        "Клиент: Здравствуйте, хочу подобрать квартиру в Москве. С чего лучше начать?\n"
        "Мы: Начнём с основных параметров. Какой бюджет рассматриваете?\n"
        "Клиент: До 15 миллионов, семейная ипотека."
    )
    assert _mop_emergency_next_question(QUESTIONS, history) == "Какой район или метро рассматриваете?"


