def test_word_parametrov_does_not_fake_previous_metro_question():
    from app.api.messenger import _mop_output_policy_violations
    history = (
        "Клиент: Здравствуйте, хочу подобрать квартиру в Москве. С чего лучше начать?\n"
        "Мы: Начнём с основных параметров. Какой бюджет рассматриваете?\n"
        "Клиент: До 15 миллионов, семейная ипотека."
    )
    problems = _mop_output_policy_violations(
        "Какой район или метро рассматриваете?",
        history,
        "",
    )
    assert "repeated_answered_question:location" not in problems
